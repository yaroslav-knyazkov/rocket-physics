"""projects/fx27/data/cspace/rockets.py -- the 3 base cspace airframes
(dev/docs/architecture-38-fx27-port.md SS38.4.1/SS38.5.2), paired with
motors.py in scenarios.py, plus their Mach-dependent ("dm") drag variants
(dev/docs/architecture-40-fx27-campaigns-and-dm-drag.md SS40.4) -- merged
into one module (architecture-44 SS44.6; the two used to be separate
`rockets.py`/`rockets_dm.py` files).

All three share one `radius=0.040` m body (fx27 data/cspace/rockets.py:
every `PointMassRocket` in this campaign uses it) -> `Aero.S = pi*r^2`,
`Aero.d_ref = 2*r`; and one `power_off_drag == power_on_drag == 0.5` ->
this project's single `Aero.C_x = 0.5` (SS38.4.1: no burn/coast split
exists here, and fx27 sets both to the same constant everywhere, so
nothing is lost).

`C_z = C_m = c_mq = 0.0` is the Option C (D-A) frozen-attitude config
itself (SS38.2.1/SS38.3.2) -- not a simplification of fx27, the same
approximation class fx27's own `PointMassRocket` runs under.

The dm section below ports the "DRAG MACH DEPENDENT" half of fx27's own
data/cspace/rockets.py that the original port scaffold never picked up
(SS40.1). Each `*_DM` Rocket is `dataclasses.replace` of its already-
ported dc sibling (`PRO54_TRANSITION`/`PRO54_EQUAL`/`PRO75`) with `aero`
swapped to `model="table"` pointing at the Mach-dependent C_A(M) table
generated by `aero/generate_dm_tables.py` (SS40.5) -- nothing else
changes: same radius/S/d_ref (same body), same `c_mq=0.0` placeholder
(carried through unedited from the dc Aero), same inert `lengths`/
`sections`/`airframe.I`/`l` (Option C, C_z=C_m=c_mq=0 is still true: the
table's own C_N/C_m columns are 0.0 at every grid point -- SS40.3).

The 4 "ideal" dm variants that used to live at the bottom of the old
`rockets_dm.py` live in `rockets_ideal.py` Section B2 (architecture-42
SS42.2/SS42.3) -- see that module, not this one, for them.
"""

from __future__ import annotations

import dataclasses
import math

from apps.sim.schema import Airframe, Rocket, Sections
from apps.sim.engine.params import Aero, Lengths

from projects.fx27._paths import cspace_aero

_RADIUS_M = 0.040  # REQ, m -- fx27 PointMassRocket(radius=0.040), all 3 cspace airframes

_AERO = Aero(
    S=math.pi * _RADIUS_M**2,  # REQ, m^2 -- reference area = pi*r^2 (rocketpy's own meaning for `radius`)
    d_ref=2.0 * _RADIUS_M,  # REQ, m -- reference length (body diameter)
    C_x=0.5,  # REQ, - -- fx27 power_off_drag == power_on_drag == 0.5 (one constant here)
    C_z=0.0,  # REQ, - -- Option C (D-A): frozen attitude, MUST be exactly 0.0 (SS38.2.1)
    C_m=0.0,  # REQ, - -- ditto
    c_mq=0.0,  # REQ, - -- ditto
)

_LENGTHS = Lengths(
    l1=1.0,  # OPT, m -- DYNAMICALLY INERT placeholder (SS38.2.1): with C_z=C_m=c_mq=0 the total
    #                    pitching moment is identically zero, so l1 never multiplies a nonzero
    #                    A_z. fx27 carries no fin/CP geometry at all (SS38.2.5), so there is no
    #                    honest value to put here either way. BECOMES A SILENT BUG if this
    #                    scenario is ever switched to an alpha-dependent aero model (R3, SS38.10).
    l2=1.0,  # OPT, m -- ditto (CoP-to-thrust-point arm; also inert, same reason)
)

_SECTIONS = Sections(
    l_motor_fwd=0.0,  # REQ, m -- zero-geometry recipe (SS38.2.8). INERT, same reason as above:
    #                            becomes a silent bug under an alpha-dependent aero model (R3).
)


def _airframe(dry_mass_kg: float) -> Airframe:
    return Airframe(
        m=dry_mass_kg,  # REQ, kg -- airframe mass, motor EXCLUDED (fx27 PointMassRocket mass=<dry>)
        I=0.5,  # REQ, kg*m^2 -- DYNAMICALLY INERT placeholder (SS38.2.1): omega_dot = M_y/I is
        #                        identically 0/I == 0 regardless of I's value; I must still be
        #                        > 0 (0.0/0.0 would be nan). BECOMES A SILENT BUG if this
        #                        scenario is ever switched to an alpha-dependent aero model
        #                        (R3, SS38.10).
        l=0.6,  # OPT, m -- placeholder CoG station; REQ in practice because the paired motor
        #                   has mass_model != "none". DYNAMICALLY INERT, same reason as I above.
    )


PRO54_TRANSITION = Rocket(
    name="pro54_transition",
    airframe=_airframe(5.835),  # REQ, kg -- fx27 data/cspace/rockets.py pro54_transition dry mass
    lengths=_LENGTHS,
    aero=_AERO,
    sections=_SECTIONS,
    notes="fx27 data/cspace/rockets.py pro54_transition; motor pro54_2060K570 (cspace/scenarios.py).",
)

PRO54_EQUAL = Rocket(
    name="pro54_equal",
    airframe=_airframe(6.393),  # REQ, kg -- fx27 data/cspace/rockets.py pro54_equal dry mass
    lengths=_LENGTHS,
    aero=_AERO,
    sections=_SECTIONS,
    notes="fx27 data/cspace/rockets.py pro54_equal; motor pro54_2060K570 (cspace/scenarios.py).",
)

PRO75 = Rocket(
    name="pro75",
    airframe=_airframe(6.225),  # REQ, kg -- fx27 data/cspace/rockets.py pro75 dry mass
    lengths=_LENGTHS,
    aero=_AERO,
    sections=_SECTIONS,
    notes="fx27 data/cspace/rockets.py pro75; motor pro75_3419L645 (cspace/scenarios.py).",
)


# --- Mach-dependent ("dm") drag variants (architecture-40 SS40.4) ---

_TABLE_PRO54_TRANSITION = cspace_aero("pro54-transition-drag.csv")
_TABLE_PRO54_EQUAL = cspace_aero("pro54-equal-drag.csv")
_TABLE_PRO75 = cspace_aero("pro75-drag.csv")


def _dm_aero(base, table_path: str):
    # REQ: swap model+table only -- S/d_ref/c_mq/cx_scale/l_p/cm_convention all carried
    # through unedited from the dc sibling's own Aero (same radius, Option C invariant
    # preserved: the table's own C_N/C_m columns are 0.0, SS40.3).
    return dataclasses.replace(base, model="table", table=table_path)


PRO54_TRANSITION_DM = dataclasses.replace(
    PRO54_TRANSITION,
    name="pro54_transition_dm",
    aero=_dm_aero(PRO54_TRANSITION.aero, _TABLE_PRO54_TRANSITION),
    notes=(
        "fx27 data/cspace/rockets.py pro54_transition_dm: Mach-dependent C_A(M) table "
        "ported from import/aerodynamics/cspace/pro54-transition-drag.csv (SS40.3/SS40.5)."
    ),
)

PRO54_EQUAL_DM = dataclasses.replace(
    PRO54_EQUAL,
    name="pro54_equal_dm",
    aero=_dm_aero(PRO54_EQUAL.aero, _TABLE_PRO54_EQUAL),
    notes=(
        "fx27 data/cspace/rockets.py pro54_equal_dm: Mach-dependent C_A(M) table ported "
        "from import/aerodynamics/cspace/pro54-equal-drag.csv (SS40.3/SS40.5)."
    ),
)

PRO75_DM = dataclasses.replace(
    PRO75,
    name="pro75_dm",
    aero=_dm_aero(PRO75.aero, _TABLE_PRO75),
    notes=(
        "fx27 data/cspace/rockets.py pro75_dm: Mach-dependent C_A(M) table ported from "
        "import/aerodynamics/cspace/pro75-drag.csv (SS40.3/SS40.5)."
    ),
)
